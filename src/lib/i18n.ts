export type UiLang = "en" | "hi";

const tables: Record<UiLang, Record<MessageKey, string>> = { en, hi };

/** Translate a key, filling {placeholders}. */
export function t(lang: UiLang, key: MessageKey, vars?: Record<string, string>): string {
  let text = tables[lang][key];
  for (const [k, v] of Object.entries(vars ?? {})) text = text.replace(`{${k}}`, v);
  return text;
}

/** Storefront labels follow the shop's language; Hinglish shops get English labels. */
export function storefrontLang(language: "en" | "hi" | "hinglish"): UiLang {
  return language === "hi" ? "hi" : "en";
}

/** "1 item" / "3 items" in the right language. */
export function itemCount(lang: UiLang, n: number): string {
  return n === 1 ? t(lang, "itemOne") : t(lang, "itemsCount", { n: String(n) });
}
